#!/usr/bin/env python3
"""
Generate Checkpoint Variables Script

This script reads the ckpts.json file generated by extract_ckpts.py and converts
the checkpoint entries into bash variable definitions that can be used in evaluation scripts.

The script converts entries from the format:
    "dataset_LoRA-MCL_model_n-hyp_rank-r": "path"

To bash variables in the format:
    CKPT_N_HYP_MODEL_DATASET=path
    CKPT_N_HYP_RANKR_DATASET=path (for wta models)
    CKPT_N_HYP_EPSILON_X_Y_DATASET=path (for relaxed-wta models)

Example usage:
    python generate_checkpoint_variables.py --input ckpts.json --output checkpoint_vars.sh
"""

import sys
import os
import json
import argparse
import re
from pathlib import Path
from typing import Dict, List, Tuple, Optional


def parse_checkpoint_key(key: str) -> Optional[Tuple[str, str, str, str, str]]:
    """
    Parse a checkpoint key to extract its components.
    
    Args:
        key: String in format "dataset_LoRA-MCL_model_n-hyp_rank-r"
        
    Returns:
        Tuple containing (dataset, model_type, epsilon_value, num_hypotheses, rank)
        Returns None if the key doesn't match expected format
    """
    try:
        # Examples:
        # clotho_LoRA-MLE_wta_1-hyp_rank-8
        # clotho_LoRA-MCL_relaxed-wta-epsilon-0.05_epsilon-0.05_5-hyp_rank-16
        # audiocaps_LoRA-MLE_wta_2-hyp_rank-32
        # audiocaps_LoRA-MCL_relaxed-wta_epsilon-0.1_3-hyp_rank-8
        
        # Split the key into components
        parts = key.split('_')
        
        # Extract dataset (first part)
        dataset = parts[0].upper()
        
        # Find the hypothesis and rank parts
        hyp_part = None
        rank_part = None
        
        for part in parts:
            if re.match(r'\d+-hyp$', part):
                hyp_part = part
            elif re.match(r'rank-\d+$', part):
                rank_part = part
        
        if not hyp_part or not rank_part:
            return None
            
        num_hypotheses = hyp_part.split('-')[0]
        rank = rank_part.split('-')[1]
        
        # Find the model specification parts (between LoRA-MCL and n-hyp)
        model_parts = []
        start_collecting = False
        
        for part in parts:
            if part == 'LoRA-MCL' or part == 'LoRA-MLE' or part == 'LoRA-MoE':
                start_collecting = True
                continue
            elif part == hyp_part or part == rank_part:
                break
            elif start_collecting:
                model_parts.append(part)
        
        # Parse model type and epsilon
        model_type = ""
        epsilon_value = ""
        
        if not model_parts:
            return None
        
        # Join all model parts and analyze
        model_string = '_'.join(model_parts)
        
        if model_string == 'wta':
            model_type = "WTA"
            epsilon_value = ""
        elif model_string == 'moe':
            model_type = "MOE"
            epsilon_value = ""
        elif 'random-wta-relaxed' in model_string:
            model_type = "RANDOM_WTA_RELAXED"
            # Look for epsilon value in the model parts
            for part in model_parts:
                if part.startswith('epsilon-'):
                    epsilon_value = part.split('-')[1]
                    break
        elif 'random-wta' in model_string:
            model_type = "RANDOM_WTA"
            epsilon_value = ""
        elif model_string.startswith('relaxed-wta'):
            model_type = "RELAXED_WTA"
            # Look for epsilon value in the model parts
            for part in model_parts:
                if part.startswith('epsilon-'):
                    epsilon_value = part.split('-')[1]
                    break
            # If no epsilon found in model parts, it might be zero or default
            if not epsilon_value:
                epsilon_value = "0.1"  # Default assumption
        else:
            # Handle other model types
            model_type = model_string.upper().replace('-', '_')
            
        return (dataset, model_type, epsilon_value, num_hypotheses, rank)
        
    except (ValueError, IndexError):
        return None


def generate_variable_name(dataset: str, model_type: str, epsilon_value: str, 
                          num_hypotheses: str, rank: str) -> str:
    """
    Generate a bash variable name from checkpoint components.
    
    Args:
        dataset: Dataset name (e.g., "AUDIOCAPS", "CLOTHO")
        model_type: Model type (e.g., "WTA", "RELAXED_WTA")
        epsilon_value: Epsilon value for relaxed models (empty for WTA)
        num_hypotheses: Number of hypotheses
        rank: LoRA rank
        
    Returns:
        Bash variable name string
    """
    if model_type == "WTA":
        if num_hypotheses == "1":
            # For 1 hypothesis WTA models, include rank in the name
            return f"CKPT_{num_hypotheses}_HYP_RANK{rank}_{dataset}"
        else:
            # For multi-hypothesis WTA models
            return f"CKPT_{num_hypotheses}_HYP_WTA_{dataset}"
    elif "ANNEALED" in model_type:
        return f"CKPT_{num_hypotheses}_HYP_ANNEALED_WTA_{dataset}"
    elif model_type == "MOE":
        return f"CKPT_{num_hypotheses}_HYP_MOE_{dataset}"
    elif model_type == "RANDOM_WTA":
        return f"CKPT_{num_hypotheses}_HYP_RANDOM_WTA_{dataset}"
    elif model_type == "RANDOM_WTA_RELAXED":
        epsilon_var = epsilon_value.replace('.', '_')
        return f"CKPT_{num_hypotheses}_HYP_RANDOM_WTA_RELAXED_EPSILON_{epsilon_var}_{dataset}"
    elif model_type == "RELAXED_WTA" and epsilon_value:
        # Convert epsilon to variable name format (replace . with _)
        epsilon_var = epsilon_value.replace('.', '_')
        return f"CKPT_{num_hypotheses}_HYP_EPSILON_{epsilon_var}_{dataset}"
    else:
        # Fallback for other model types
        return f"CKPT_{num_hypotheses}_HYP_{model_type}_{dataset}"


def generate_checkpoint_variables(ckpts_dict: Dict[str, str]) -> List[str]:
    """
    Generate bash variable definitions from checkpoint dictionary.
    
    Args:
        ckpts_dict: Dictionary mapping checkpoint keys to paths
        
    Returns:
        List of bash variable definition strings
    """
    variables = []
    
    for key, path in ckpts_dict.items():
        parsed = parse_checkpoint_key(key)
        if parsed is None:
            print(f"Warning: Could not parse checkpoint key: {key}")
            continue
            
        dataset, model_type, epsilon_value, num_hypotheses, rank = parsed
        var_name = generate_variable_name(dataset, model_type, epsilon_value, 
                                        num_hypotheses, rank)
        
        variables.append(f'{var_name}="{path}"')
    
    return sorted(variables)


def main():
    """
    Main function to run the checkpoint variable generation script.
    
    Command line arguments:
        --input: Input JSON file path (default: 'ckpts.json')
        --output: Output shell script file path (default: 'checkpoint_vars.sh')
        --format: Output format ('bash' or 'export') (default: 'bash')
    
    Example usage:
        python generate_checkpoint_variables.py --input ckpts.json --output vars.sh
    """
    parser = argparse.ArgumentParser(
        description="Generate bash variables from checkpoint JSON file"
    )
    parser.add_argument(
        "--input",
        type=str,
        default='ckpts.json',
        help="Input JSON file path",
    )
    parser.add_argument(
        "--output",
        type=str,
        default='checkpoint_vars.sh',
        help="Output shell script file path",
    )
    parser.add_argument(
        "--format",
        type=str,
        choices=["bash", "export"],
        default="bash",
        help="Output format: 'bash' for simple assignment, 'export' for exported variables",
    )
    
    args = parser.parse_args()
    
    # Read checkpoint JSON file
    try:
        with open(args.input, 'r') as f:
            ckpts_dict = json.load(f)
    except FileNotFoundError:
        print(f"Error: Input file '{args.input}' not found")
        return 1
    except json.JSONDecodeError as e:
        print(f"Error: Invalid JSON in '{args.input}': {e}")
        return 1
    
    # Generate variable definitions
    variables = generate_checkpoint_variables(ckpts_dict)
    
    if not variables:
        print("Warning: No valid checkpoint entries found")
        return 0
    
    # Write output file
    try:
        with open(args.output, 'w') as f:
            f.write("#!/bin/bash\n")
            f.write("# Auto-generated checkpoint variable definitions\n")
            f.write(f"# Generated from: {args.input}\n\n")
            
            for var in variables:
                if args.format == "export":
                    f.write(f"export {var}\n")
                else:
                    f.write(f"{var}\n")
                    
        print(f"Generated {len(variables)} checkpoint variables in '{args.output}'")
        
    except IOError as e:
        print(f"Error: Could not write to '{args.output}': {e}")
        return 1
    
    return 0


if __name__ == "__main__":
    sys.exit(main())
